import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import puppeteer from 'puppeteer';
import {USER_COUNT, fixtureWallet, seedAdminSpeedFixture} from './admin-speed-fixture.js';

const app = path.resolve(import.meta.dirname, '..');
const artifact = path.resolve(app, '../../tools/admin-speed-20261012');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'wg-admin-speed-browser-'));
const result = {isolatedSyntheticData:true, userCount:USER_COUNT, scenarios:[], runtimeErrors:[], unexpectedWrites:[]};
const mark = message => {result.scenarios.push(message); console.log('PASS: ' + message);};
let child, browser;
try {
  seedAdminSpeedFixture(root);
  const env = Object.fromEntries(['PATH','Path','SystemRoot','WINDIR','TEMP','TMP','APPDATA','LOCALAPPDATA','USERPROFILE','COMSPEC'].filter(name => process.env[name]).map(name => [name,process.env[name]]));
  Object.assign(env, {WG_DATA_DIR:root, PORT:'0', HOST:'127.0.0.1', DE_MODE:'paper', EX_MODE:'paper', RS_MODE:'paper', PLATFORM_ADMIN_USERNAME:'speed-operator', PLATFORM_ADMIN_PASSWORD:'TEST_ONLY_SPEED_PASSWORD', WALLET_ADMIN_TOKEN:'TEST_ONLY_SPEED_FUNDS'});
  child = spawn(process.execPath, ['src/server.js'], {cwd:app, env, stdio:['ignore','pipe','pipe'], windowsHide:true});
  let log = '';
  const base = await new Promise((resolve,reject) => {
    const timer = setTimeout(() => reject(new Error('isolated server startup timeout')), 25000);
    child.stdout.on('data', data => {log += data; const match = log.match(/http:\/\/127\.0\.0\.1:\d+/); if (match) {clearTimeout(timer); resolve(match[0]);}});
    child.stderr.on('data', data => {log += data;});
    child.once('exit', code => {clearTimeout(timer); reject(new Error('isolated server exited: ' + code + '; ' + log.slice(-700)));});
  });
  assert.equal((await fetch(base + '/api/admin/tokens')).status,401);
  browser = await puppeteer.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless:true});
  async function openAdmin(baseline = false) {
    const page = await browser.newPage();
    await page.setViewport({width:1440, height:1000});
    await page.evaluateOnNewDocument(() => {
      window.adminLongTasks = [];
      new PerformanceObserver(list => {for (const entry of list.getEntries()) adminLongTasks.push(Math.round(entry.duration));}).observe({type:'longtask', buffered:true});
    });
    page.on('pageerror', error => result.runtimeErrors.push(error.message));
    const requests = [], held = new Map();
    let holdRule = null;
    await page.setRequestInterception(true);
    page.on('request', request => {
      const url = new URL(request.url());
      if (url.origin !== base) return request.abort();
      if (!['GET','HEAD','OPTIONS'].includes(request.method()) && !['/api/admin/login','/api/admin/logout'].includes(url.pathname)) {result.unexpectedWrites.push(url.pathname); return request.abort();}
      if (url.pathname.startsWith('/api/')) requests.push(url.pathname + url.search);
      if (baseline && url.pathname === '/js/operator-admin.js') return request.respond({contentType:'application/javascript', body:fs.readFileSync(path.join(artifact,'before/public/js/operator-admin.js'),'utf8')});
      if (holdRule?.(url)) {held.set(url.pathname + url.search, request); return;}
      return request.continue();
    });
    await page.goto(base + '/admin.html', {waitUntil:'domcontentloaded'});
    await page.waitForFunction(() => document.activeElement?.id === 'admin-username');
    await page.type('#admin-username', 'speed-operator'); await page.type('#admin-password', 'TEST_ONLY_SPEED_PASSWORD');
    const start = performance.now();
    await page.click('#admin-login-button');
    await page.waitForFunction(() => !document.getElementById('admin-app').hidden && document.getElementById('admin-updated').textContent.startsWith('更新于'));
    const metrics = await page.evaluate(() => ({nodes:document.querySelectorAll('*').length, hiddenUserRows:document.querySelectorAll('#admin-users-body tr').length, hiddenDepositRows:document.querySelectorAll('#admin-deposits-body tr').length, longTasks:adminLongTasks}));
    metrics.firstDataReadyMs = Math.round(performance.now() - start);
    return {page, requests, held, metrics, hold:rule => {holdRule = rule;}};
  }
  const baseline = await openAdmin(true);
  result.frontendBefore = baseline.metrics;
  await baseline.page.click('#admin-logout'); await baseline.page.close();
  const candidate = await openAdmin();
  const {page, requests, held, hold} = candidate;
  result.frontendAfter = candidate.metrics;
  assert.equal(candidate.metrics.hiddenUserRows, 0); assert.equal(candidate.metrics.hiddenDepositRows, 0);
  assert(candidate.metrics.nodes < 2000);
  assert(requests.includes('/api/admin/dashboard?view=overview'));
  assert(!requests.some(url => /^\/api\/admin\/(users|deposits|lottery|a-token)\b/.test(url)));
  assert.equal(await page.$eval('#metric-wallet-users', node => node.textContent), String(USER_COUNT));
  mark('overview loads only its own data and creates no hidden user/deposit tables');
  const rowCount = count => page.waitForFunction(count => document.querySelector('[data-admin-panel="users"]').classList.contains('active') && document.querySelectorAll('#admin-users-body [data-detail-btn]').length === count && !document.getElementById('admin-user-count').textContent.includes('正在'), {}, count);
  await page.click('[data-admin-page="users"]'); await rowCount(50);
  const first = await page.$$eval('[data-detail-btn]', nodes => nodes.map(node => node.dataset.detailBtn));
  await page.click('#admin-users-next'); await page.waitForFunction(() => document.getElementById('admin-users-page-status').textContent.startsWith('第 51')); await rowCount(50);
  const next = await page.$$eval('[data-detail-btn]', nodes => nodes.map(node => node.dataset.detailBtn));
  assert.equal(new Set([...first,...next]).size,100);
  await page.click('#admin-users-prev'); await page.waitForFunction(() => document.getElementById('admin-users-page-status').textContent.startsWith('第 1–'));
  assert.deepEqual(await page.$$eval('[data-detail-btn]', nodes => nodes.map(node => node.dataset.detailBtn)), first);
  await page.screenshot({path:path.join(artifact,'users-desktop.png'), fullPage:true});
  mark('actual users endpoint pages 50 users and next/previous preserve all records');
  const setSearch = async value => page.$eval('#admin-user-search', (node,value) => {node.value=value; node.dispatchEvent(new Event('input',{bubbles:true}));}, value);
  const searchStart = requests.length;
  await page.focus('#admin-user-search'); await page.type('#admin-user-search', fixtureWallet(42).toUpperCase(), {delay:1}); await rowCount(1);
  assert.equal(requests.slice(searchStart).filter(url => url.startsWith('/api/admin/users?')).length,1);
  assert.equal(await page.$eval('[data-detail-btn]', node => node.dataset.detailBtn), fixtureWallet(42));
  await setSearch(''); await rowCount(50); await page.click('#admin-real-only');
  await page.waitForFunction(total => document.getElementById('admin-user-count').textContent === total + ' 位用户', {}, USER_COUNT - 1);
  mark('debounced server search works across all pages and the real-user filter retains totals');
  hold(url => url.pathname === '/api/admin/users' && url.searchParams.get('q') === 'stale-test');
  await setSearch('stale-test');
  await page.waitForFunction(() => document.getElementById('admin-user-count').textContent.includes('正在'));
  await new Promise(resolve => setTimeout(resolve,50));
  assert.equal(held.size,1);
  await setSearch(fixtureWallet(80)); await rowCount(1);
  await held.values().next().value.respond({contentType:'application/json', body:JSON.stringify({total:1, offset:0, users:[{address:'stale-response', platformUsdtBalance:'999'}]})}); held.clear(); hold(null);
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert.equal(await page.$eval('[data-detail-btn]', node => node.dataset.detailBtn), fixtureWallet(80));
  mark('an older search response cannot overwrite a newer result');
  const lazyStart = requests.length;
  await page.click('[data-admin-page="tokens"]'); await page.waitForSelector('#admin-tokens-body tr td');
  await page.click('[data-admin-page="stocks"]'); await page.waitForSelector('#admin-stocks-body tr td');
  assert(!requests.slice(lazyStart).some(url => url.startsWith('/api/admin/dashboard')));
  await page.click('[data-admin-page="deposits"]'); await page.waitForFunction(() => document.querySelectorAll('#admin-deposits-body tr').length === 19);
  mark('tokens, stocks and deposits read their own endpoints after navigation');
  await page.click('[data-admin-page="a-kline"]'); await page.waitForSelector('#a-save-mode');
  await page.click('[data-admin-page="a-miner"]'); await page.waitForSelector('#am-open-funds');
  const minerStart = requests.length;
  hold(url => url.pathname === '/api/admin/a-token/miners');
  await page.click('#admin-refresh'); await page.click('#admin-refresh');
  await new Promise(resolve => setTimeout(resolve,50));
  assert.equal(requests.slice(minerStart).filter(url => url === '/api/admin/a-token/miners').length,1);
  assert.equal(held.size,1);
  await held.values().next().value.continue(); held.clear(); hold(null);
  await page.waitForFunction(() => document.getElementById('am-tbody')?.childElementCount > 0);
  mark('AIX kline/miner pages remain functional and simultaneous refreshes share one request');
  let lotteryStart = requests.length;
  await page.click('[data-admin-page="lottery"]'); await page.waitForSelector('[data-prob]');
  assert.deepEqual(requests.slice(lotteryStart).filter(url => url.startsWith('/api/admin/lottery/')), ['/api/admin/lottery/prizes']);
  lotteryStart = requests.length;
  await page.click('[data-al-tab="social"]'); await page.waitForSelector('#al-social-status');
  assert.deepEqual(requests.slice(lotteryStart).filter(url => url.startsWith('/api/admin/lottery/')), ['/api/admin/lottery/social?status=pending']);
  lotteryStart = requests.length;
  await page.click('[data-al-tab="topup"]'); await page.waitForSelector('#al-topup-wallet');
  assert.equal(requests.slice(lotteryStart).filter(url => url.startsWith('/api/admin/lottery/')).length,0);
  await page.click('[data-al-tab="assigned"]'); await page.waitForSelector('#al-assign-wallet');
  assert(requests.slice(lotteryStart).includes('/api/admin/lottery/assigned?status=pending'));
  mark('lottery loads only selected subtab data; assigned awards also load the prize list');
  await page.click('[data-admin-page="support"]'); await page.waitForFunction(() => document.getElementById('admin-support-ticket-list').textContent.includes('暂无会话'));
  await page.click('[data-admin-page="agents"]'); await page.waitForFunction(() => document.getElementById('admin-agents-list').textContent.includes('暂无代理'));
  const agentStart = requests.length; await page.click('#admin-refresh');
  await page.waitForFunction(() => document.getElementById('admin-agents-list-status').textContent === '');
  assert(requests.slice(agentStart).includes('/api/admin/agents'));
  mark('support and agents load independently and the global refresh updates agents');
  await setSearch(''); await page.click('[data-admin-page="users"]'); await rowCount(50);
  await page.setViewport({width:390,height:844,isMobile:true,hasTouch:true});
  await page.waitForFunction(() => !document.getElementById('admin-app').hidden && document.getElementById('admin-updated').textContent.startsWith('更新于'));
  await page.click('#admin-menu-toggle');
  await page.waitForFunction(() => document.body.classList.contains('admin-nav-open') && document.getElementById('admin-sidebar').getBoundingClientRect().left >= -1);
  await page.click('[data-admin-page="users"]'); await rowCount(50);
  await page.waitForFunction(() => !document.body.classList.contains('admin-nav-open') && document.getElementById('admin-sidebar').getBoundingClientRect().right <= 1);
  await page.screenshot({path:path.join(artifact,'users-mobile.png')});
  await page.$eval('#admin-users-next',node => node.scrollIntoView({block:'center'}));
  await page.screenshot({path:path.join(artifact,'users-mobile-pager.png')});
  const pager = await page.$eval('#admin-users-next', node => {const rect=node.getBoundingClientRect(); return {x:rect.left,right:rect.right,width:innerWidth};});
  assert(pager.x >= 0 && pager.right <= pager.width);
  mark('50-row users list and pager work on mobile');
  hold(url => url.pathname === '/api/admin/users');
  await page.click('#admin-refresh'); await page.waitForFunction(() => document.getElementById('admin-user-count').textContent.includes('正在'));
  await new Promise(resolve => setTimeout(resolve,50)); assert.equal(held.size,1);
  await page.click('#admin-menu-toggle');
  await page.waitForFunction(() => document.body.classList.contains('admin-nav-open') && document.getElementById('admin-sidebar').getBoundingClientRect().left >= -1);
  await page.click('#admin-logout'); await page.waitForFunction(() => document.getElementById('admin-app').hidden);
  await held.values().next().value.respond({contentType:'application/json',body:JSON.stringify({total:1,offset:0,users:[{address:fixtureWallet(0),platformUsdtBalance:'999'}]})});
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert.equal(await page.$eval('#admin-users-body',node => node.childElementCount),0);
  assert.deepEqual(result.runtimeErrors,[]); assert.deepEqual(result.unexpectedWrites,[]);
  mark('logout clears loaded data and rejects pending user responses; no financial writes occurred');
  result.passed = true;
} catch (error) {
  result.error = error.stack; console.error(error); process.exitCode = 1;
} finally {
  if (browser) await browser.close();
  if (child && child.exitCode === null) {const exited=once(child,'exit'); child.kill(); await exited;}
  fs.rmSync(root, {recursive:true,force:true});
  fs.writeFileSync(path.join(artifact,'browser-test.json'), JSON.stringify(result,null,2));
  console.log(JSON.stringify({passed:result.passed, frontendBefore:result.frontendBefore, frontendAfter:result.frontendAfter, runtimeErrors:result.runtimeErrors},null,2));
}
