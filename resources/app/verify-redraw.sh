#!/bin/bash
DB="sqlite3 file:///var/lib/wg-platform/wg-platform.sqlite?mode=ro"
echo "=== 1. 4h K 线（应多根小阳线） ==="
$DB "SELECT datetime(time,'unixepoch','+8 hours'), printf('O:%.6f H:%.6f L:%.6f C:%.6f',open,high,low,close) FROM a_token_klines WHERE period='4h' ORDER BY time DESC LIMIT 8;"
echo "=== 2. 1d K 线（今日大阳线） ==="
$DB "SELECT datetime(time,'unixepoch','+8 hours'), printf('O:%.6f H:%.6f L:%.6f C:%.6f',open,high,low,close) FROM a_token_klines WHERE period='1d' ORDER BY time DESC LIMIT 3;"
