$DB "SELECT datetime(time,'unixepoch','+8 hours'), printf('O:%.6f C:%.6f',open,close) FROM a_token_klines WHERE period='15m' ORDER BY time DESC LIMIT 12;"
echo "=== 4. 5m 最近 8 根 ==="
$DB "SELECT datetime(time,'unixepoch','+8 hours'), printf('O:%.6f C:%.6f',open,close) FROM a_token_klines WHERE period='5m' ORDER BY time DESC LIMIT 8;"
echo "=== 5. 1m 最近 5 根（tick 正常推进） ==="
$DB "SELECT datetime(time,'unixepoch','+8 hours'), printf('O:%.6f C:%.6f',open,close) FROM a_token_klines WHERE period='1m' ORDER BY time DESC LIMIT 5;"
